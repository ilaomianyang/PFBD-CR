def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _scenario_base_type(name: str) -> str:
    return {
        "low_spike": "spike",
        "low_offset": "offset",
        "slow_drift": "drift",
        "short_lag": "time_shift",
        "long_stuck": "stuck",
        "low_noise": "gaussian_noise",
        "coordinated_offset": "offset",
    }[name]


def _split_positions(frame: pd.DataFrame, station_id: str, split: str) -> pd.DataFrame:
    part = frame[frame["station_id"].astype(str).eq(str(station_id))].copy()
    part = part.sort_values("timestamp_utc", kind="stable").reset_index()
    return part[
        part["split"].eq(split) & part["observation_present"].astype(bool)
    ].copy()


def make_simulated_blocks(
    frame: pd.DataFrame, protocol: dict, seed: int, split: str, offset: int
) -> pd.DataFrame:
    """Create non-overlapping blocks from the frozen scenario list.

    Scenario positions are selected from observed rows only.  The coordinated
    scenario uses the same relative start index for the first two stations in
    the frozen station order; all other scenarios are station-local.
    """
    if split not in {"valid", "test"}:
        raise ValueError("split must be valid or test")
    rng = np.random.default_rng(int(seed) + int(offset))
    # Reserve coordinated blocks first so sparse stations cannot consume all
    # valid rows before the two-station scenario is placed.  The protocol
    # freezes the scenario set and RNG stream, not an implementation-specific
    # iteration order.
    scenarios = sorted(
        list(protocol["attack_scenarios"]),
        key=lambda item: (not bool(item.get("coordinated")), str(item["name"])),
    )
    stations = sorted(frame["station_id"].astype(str).unique().tolist())
    available_by_station = {
        station_id: _split_positions(frame, station_id, split)["index"].to_numpy(dtype=int).tolist()
        for station_id in stations
    }
    rows: list[dict[str, object]] = []
    for scenario in scenarios:
        length = int(scenario["length"])
        scenario_name = str(scenario["name"])
        if scenario.get("coordinated"):
            if len(stations) < 2:
                raise RuntimeError("coordinated scenario requires two stations")
            pair = stations[:2]
            if any(len(available_by_station[s]) < length for s in pair):
                raise RuntimeError(f"not enough {split} rows for coordinated scenario {scenario_name}")
            first_by_time = {
                frame.loc[int(pos), "timestamp_utc"]: int(pos)
                for pos in available_by_station[pair[0]]
            }
            second_by_time = {
                frame.loc[int(pos), "timestamp_utc"]: int(pos)
                for pos in available_by_station[pair[1]]
            }
            common_times = sorted(set(first_by_time).intersection(second_by_time))
            if len(common_times) < length:
                raise RuntimeError(f"not enough shared timestamps for coordinated scenario {scenario_name}")
            start = int(rng.integers(0, len(common_times) - length + 1))
            chosen_times = common_times[start : start + length]
            chosen_by_station = {
                pair[0]: [first_by_time[ts] for ts in chosen_times],
                pair[1]: [second_by_time[ts] for ts in chosen_times],
            }
            target_stations = pair
        else:
            target_stations = stations
            chosen_by_station = {}
            for station_id in target_stations:
                available = available_by_station[station_id]
                if len(available) < length:
                    raise RuntimeError(f"not enough {split} rows for {station_id}/{scenario_name}")
                start = int(rng.integers(0, len(available) - length + 1))
                chosen_by_station[station_id] = available[start : start + length]
        for station_id in target_stations:
            chosen = chosen_by_station[station_id]
            if len(chosen) != length:
                raise RuntimeError("simulated block length mismatch")
            ordered = _split_positions(frame, station_id, split)
            index_to_local = {int(value): i for i, value in enumerate(ordered["index"].to_numpy(dtype=int))}
            for pos in chosen:
                row = frame.loc[int(pos)]
                source_pos = -1
                if scenario["base_type"] == "time_shift":
                    loc = index_to_local[int(pos)]
                    lag = int(scenario["lag_rows"])
                    source_loc = loc - lag
                    if source_loc < 0:
                        raise RuntimeError(f"{station_id}/{scenario_name} lacks clean lag history")
                    source_pos = int(ordered.iloc[source_loc]["index"])
                rows.append({
                    "station_id": str(station_id),
                    "split": split,
                    "seed": int(seed),
                    "scenario": scenario_name,
                    "attack_type": _scenario_base_type(scenario_name),
                    "row_position": int(pos),
                    "source_row_position": int(source_pos),
                    "timestamp_utc": row["timestamp_utc"],
                })
            chosen_set = set(int(value) for value in chosen)
            available_by_station[station_id] = [
                value for value in available_by_station[station_id] if value not in chosen_set
            ]
    return pd.DataFrame(rows)


def inject_simulated_attack(frame: pd.DataFrame, blocks: pd.DataFrame, scenario_by_name: dict) -> pd.DataFrame:
    attacked = frame.copy()
    values = pd.to_numeric(frame["temperature_c"], errors="coerce").to_numpy(dtype=float).copy()
    clean = values.copy()
    attacked["is_attack"] = False
    attacked["attack_type"] = "normal"
    attacked["attack_scenario"] = "normal"
    attacked["attack_event_id"] = ""
    for (station_id, scenario_name), part in blocks.groupby(["station_id", "scenario"], sort=True):
        scenario = scenario_by_name[str(scenario_name)]
        positions = part["row_position"].to_numpy(dtype=int)
        base_type = _scenario_base_type(str(scenario_name))
        if base_type == "spike":
            values[positions] += float(scenario["magnitude"])
        elif base_type == "offset":
            values[positions] += float(scenario["magnitude"])
        elif base_type == "drift":
            values[positions] += np.linspace(float(scenario["start"]), float(scenario["end"]), len(positions))
        elif base_type == "time_shift":
            source = part["source_row_position"].to_numpy(dtype=int)
            source_values = clean[source]
            if not np.isfinite(source_values).all():
                source_values = pd.Series(clean).ffill().bfill().to_numpy(dtype=float)[source]
            values[positions] = source_values
        elif base_type == "stuck":
            first = clean[positions[0]]
            if not np.isfinite(first):
                first = float(pd.Series(clean).ffill().bfill().iloc[positions[0]])
            values[positions] = first
        elif base_type == "gaussian_noise":
            seed_material = f"{int(part['seed'].iloc[0])}|{station_id}|{scenario_name}".encode("utf-8")
            stable_offset = int.from_bytes(hashlib.sha256(seed_material).digest()[:8], "big") % 1000003
            seed = int(part["seed"].iloc[0]) + stable_offset
            rng = np.random.default_rng(seed)
            values[positions] += rng.normal(0.0, float(scenario["sigma"]), size=len(positions))
        attacked.loc[positions, "is_attack"] = True
        attacked.loc[positions, "attack_type"] = base_type
        attacked.loc[positions, "attack_scenario"] = str(scenario_name)
        attacked.loc[positions, "attack_event_id"] = [
            f"{station_id}__{scenario_name}__{int(part['seed'].iloc[0])}"
        ] * len(positions)
    attacked["temperature_c"] = values
    attacked["observed_value"] = pd.to_numeric(attacked["temperature_c"], errors="coerce")
    attacked["station_key"] = attacked["station_id"].astype(str)
    return attacked



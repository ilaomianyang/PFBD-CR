def _bootstrap_ci(values: np.ndarray, rng: np.random.Generator) -> tuple[float, float]:
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    if values.size == 0:
        return float("nan"), float("nan")
    draws = rng.choice(values, size=(BOOTSTRAP_ITERATIONS, values.size), replace=True).mean(axis=1)
    return float(np.quantile(draws, 0.025)), float(np.quantile(draws, 0.975))


def _paired_bootstrap(station: pd.DataFrame, candidate: str, baseline: str, metric: str, rng: np.random.Generator) -> tuple[float, float, float]:
    left = station[station["method"].eq(candidate)][["source", "seed", "station_id", metric]].rename(columns={metric: "left"})
    right = station[station["method"].eq(baseline)][["source", "seed", "station_id", metric]].rename(columns={metric: "right"})
    aligned = left.merge(right, on=["source", "seed", "station_id"], validate="one_to_one")
    diff = (aligned["left"] - aligned["right"]).to_numpy(dtype=float)
    diff = diff[np.isfinite(diff)]
    if diff.size == 0:
        return float("nan"), float("nan"), float("nan")
    draws = rng.choice(diff, size=(BOOTSTRAP_ITERATIONS, diff.size), replace=True).mean(axis=1)
    point = float(diff.mean())
    lo = float(np.quantile(draws, 0.025))
    hi = float(np.quantile(draws, 0.975))
    p = float(2.0 * min(np.mean(draws <= 0.0), np.mean(draws >= 0.0)))
    return point, lo, min(1.0, p)


def _bh(values: list[float]) -> list[float]:
    p = np.asarray(values, dtype=float)
    q = np.full(len(p), np.nan, dtype=float)
    finite = np.isfinite(p)
    if not finite.any():
        return q.tolist()
    order = np.argsort(p[finite])
    ranked = p[finite][order]
    adjusted = ranked * len(ranked) / np.arange(1, len(ranked) + 1)
    adjusted = np.minimum.accumulate(adjusted[::-1])[::-1]
    target = np.empty_like(adjusted)
    target[order] = np.minimum(adjusted, 1.0)
    q[finite] = target
    return q.tolist()


def main() -> int:
    started = time.perf_counter()
    protocol = load_json(PROTOCOL_PATH)
    scenario_by_name = {str(row["name"]): row for row in protocol["attack_scenarios"]}
    evaluation_rows: list[dict[str, object]] = []
    station_rows: list[dict[str, object]] = []
    type_rows: list[dict[str, object]] = []
    scenario_rows: list[dict[str, object]] = []
    selection_rows: list[dict[str, object]] = []
    fit_rows: list[dict[str, object]] = []
    pooled_raw: dict[str, dict[str, list[np.ndarray]]] = {
        method: {"y": [], "score": []} for method in METHODS
    }
    for source, protocol_path in PROTOCOLS.items():
        print(json.dumps({"event": "provider_start", "source": source}, ensure_ascii=False), flush=True)
        source_started = time.perf_counter()
        source_protocol = load_json(protocol_path)
        frame = make_frame(source, source_protocol)
        base = detector_frame(frame)
        detectors = fit_detectors(base, source_protocol)
        train_normal = (base["split"].eq("train") & base["observation_present"]).to_numpy(dtype=bool)
        base_components = score_components(base, detectors)
        base_fused, _ = fuse_scores(base, base_components)
        base_z = robust_standardize(base_fused, train_normal).to_numpy(dtype=float)
        base_features = candidate_features(base, train_normal)
        base_matrix, feature_names = feature_matrix(base_components, base_features, train_normal)
        fit_started = time.perf_counter()
        fitted_old = fit_baselines(base, base_matrix, train_normal)
        fitted_light, light_info = fit_lightweight_baselines(base, base_matrix, train_normal)
        fitted_security, security_info = fit_security_baselines(base, base_matrix, train_normal)
        fit_elapsed = time.perf_counter() - fit_started
        fit_rows.append({"source": source, "train_normal_rows": int(train_normal.sum()), "feature_count": int(base_matrix.shape[1]), "feature_names": json.dumps(feature_names), "fit_seconds": fit_elapsed, "total_source_seconds_so_far": time.perf_counter() - source_started, "lightweight_info": json.dumps(light_info, default=str), "security_info": json.dumps(security_info, default=str)})
        primary_far = float(protocol["primary_far"])
        for seed in protocol["seeds"]:
            seed = int(seed)
            seed_started = time.perf_counter()
            valid_blocks = make_simulated_blocks(base, protocol, seed, "valid", VALID_OFFSET)
            test_blocks = make_simulated_blocks(base, protocol, seed, "test", TEST_OFFSET)
            valid_attacked = inject_simulated_attack(base, valid_blocks, scenario_by_name)
            test_attacked = inject_simulated_attack(base, test_blocks, scenario_by_name)
            valid_components = score_components(valid_attacked, detectors)
            test_components = score_components(test_attacked, detectors)
            valid_fused, _ = fuse_scores(valid_attacked, valid_components)
            test_fused, _ = fuse_scores(test_attacked, test_components)
            valid_base_z = robust_standardize(valid_fused, train_normal).to_numpy(dtype=float)
            test_base_z = robust_standardize(test_fused, train_normal).to_numpy(dtype=float)
            valid_features = candidate_features(valid_attacked, train_normal)
            test_features = candidate_features(test_attacked, train_normal)
            valid_matrix, _ = feature_matrix(valid_components, valid_features, train_normal)
            test_matrix, _ = feature_matrix(test_components, test_features, train_normal)
            valid_mask = valid_attacked["split"].eq("valid").to_numpy(dtype=bool)
            test_mask = test_attacked["split"].eq("test").to_numpy(dtype=bool)
            valid_frame = valid_attacked.loc[valid_mask].reset_index(drop=True)
            test_frame = test_attacked.loc[test_mask].reset_index(drop=True)
            valid_normal = (valid_frame["observation_present"] & ~valid_frame["is_attack"]).to_numpy(dtype=bool)
            if not valid_frame["is_attack"].any() or not test_frame["is_attack"].any():
                raise RuntimeError(f"{source}/{seed}: empty simulated attack split")
            valid_base = valid_base_z[valid_mask]
            test_base = test_base_z[test_mask]
            valid_feature_masked = {key: values[valid_mask] for key, values in valid_features.items()}
            test_feature_masked = {key: values[test_mask] for key, values in test_features.items()}
            valid_old = score_baselines(fitted_old, valid_matrix[valid_mask])
            test_old = score_baselines(fitted_old, test_matrix[test_mask])
            valid_light = score_lightweight_baselines(fitted_light, valid_matrix[valid_mask])
            test_light = score_lightweight_baselines(fitted_light, test_matrix[test_mask])
            valid_security = score_security_baselines(fitted_security, valid_frame, valid_matrix[valid_mask])
            test_security = score_security_baselines(fitted_security, test_frame, test_matrix[test_mask])
            valid_scores: dict[str, np.ndarray] = {}
            test_scores: dict[str, np.ndarray] = {}
            for method, rule in SELECTION_RULES.items():
                selected = select_candidate_stage244(rule, valid_base, valid_feature_masked, valid_frame, valid_normal, primary_far)
                key = (str(selected["feature"]), int(selected["window"]))
                valid_scores[method] = (1.0 - float(selected["weight"])) * valid_base + float(selected["weight"]) * valid_feature_masked[key]
                test_scores[method] = (1.0 - float(selected["weight"])) * test_base + float(selected["weight"]) * test_feature_masked[key]
                selection_rows.append({"source": source, "seed": seed, "method": method, "rule": rule, "feature": selected["feature"], "window": int(selected["window"]), "weight": float(selected["weight"]), "valid_f1": float(selected["valid_f1"]), "valid_event_macro": float(selected["valid_event_macro"]), "valid_nonstuck_event_macro": float(selected["valid_nonstuck_event_macro"])})
            valid_scores.update(valid_old)
            test_scores.update(test_old)
            valid_scores.update(valid_light)
            test_scores.update(test_light)
            valid_scores.update(valid_security)
            test_scores.update(test_security)
            y_test = test_frame["is_attack"].astype(bool).to_numpy()
            for method in METHODS:
                valid_score = np.asarray(valid_scores[method], dtype=float)
                test_score = np.asarray(test_scores[method], dtype=float)
                threshold = far_threshold(valid_score, valid_normal, primary_far)
                predicted = test_frame["observation_present"].to_numpy(dtype=bool) & (test_score >= threshold)
                row_metrics = metrics(y_test, predicted, test_score)
                event_values = event_metrics(test_frame, predicted)
                type_values = type_metrics(test_frame, predicted, test_score)
                evaluation_rows.append({"source": source, "seed": seed, "method": method, "threshold": float(threshold), **row_metrics, **event_values})
                for attack_type, values in type_values.items():
                    type_rows.append({"source": source, "seed": seed, "method": method, "attack_type": attack_type, **values})
                scenario_labels = test_frame["attack_scenario"].astype(str).to_numpy()
                for scenario_name in sorted(set(scenario_labels[y_test])):
                    scenario_mask = y_test & (scenario_labels == scenario_name)
                    scenario_event = test_frame.loc[scenario_mask, ["attack_event_id"]].copy()
                    scenario_event["predicted"] = predicted[scenario_mask]
                    grouped = scenario_event.groupby("attack_event_id", sort=True)["predicted"].any()
                    scenario_rows.append({
                        "source": source,
                        "seed": seed,
                        "method": method,
                        "scenario": scenario_name,
                        "attack_rows": int(scenario_mask.sum()),
                        "detected_rows": int(predicted[scenario_mask].sum()),
                        "row_recall": float(predicted[scenario_mask].mean()) if scenario_mask.any() else 0.0,
                        "events": int(len(grouped)),
                        "detected_events": int(grouped.sum()),
                        "event_coverage": float(grouped.mean()) if len(grouped) else 0.0,
                    })
                for row in station_metrics(test_frame, predicted):
                    denominator = 2 * int(row["tp"]) + int(row["fp"]) + int(row["fn"])
                    row["f1"] = float(2 * int(row["tp"]) / denominator) if denominator else 0.0
                    row["precision"] = float(int(row["tp"]) / (int(row["tp"]) + int(row["fp"]))) if (int(row["tp"]) + int(row["fp"])) else 0.0
                    station_rows.append({"source": source, "seed": seed, "method": method, **row})
                pooled_raw[method]["y"].append(y_test.copy())
                pooled_raw[method]["score"].append(test_score.copy())
            print(json.dumps({"event": "seed_complete", "source": source, "seed": seed, "elapsed_seconds": time.perf_counter() - seed_started}, ensure_ascii=False), flush=True)
    evaluation = pd.DataFrame(evaluation_rows)
    station = pd.DataFrame(station_rows)
    types = pd.DataFrame(type_rows)
    scenarios = pd.DataFrame(scenario_rows)
    selection = pd.DataFrame(selection_rows)
    fit = pd.DataFrame(fit_rows)
    rng = np.random.default_rng(BOOTSTRAP_SEED)
    comparisons: list[dict[str, object]] = []
    for candidate in TRUST_METHODS:
        for baseline in BASELINE_METHODS:
            for metric_name in ["event_coverage", "f1"]:
                point, lo, p = _paired_bootstrap(station, candidate, baseline, metric_name, rng)
                comparisons.append({"candidate": candidate, "baseline": baseline, "metric": metric_name, "difference": point, "ci95_low": lo, "ci95_high": None, "p_two_sided": p})
    pvals = [float(row["p_two_sided"]) for row in comparisons]
    qvals = _bh(pvals)
    for row, q in zip(comparisons, qvals):
        row["bh_q"] = q
        row["supported"] = bool(np.isfinite(row["difference"]) and np.isfinite(row["ci95_low"]) and row["ci95_low"] > 0.0 and q < 0.05)
    compare_df = pd.DataFrame(comparisons)
    # Compute the upper CI in a separate pass so the JSON/CSV never hides it.
    for idx, row in compare_df.iterrows():
        candidate = row["candidate"]
        baseline = row["baseline"]
        metric_name = row["metric"]
        left = station[station["method"].eq(candidate)][["source", "seed", "station_id", metric_name]].rename(columns={metric_name: "left"})
        right = station[station["method"].eq(baseline)][["source", "seed", "station_id", metric_name]].rename(columns={metric_name: "right"})
        diff = (left.merge(right, on=["source", "seed", "station_id"], validate="one_to_one")["left"] - left.merge(right, on=["source", "seed", "station_id"], validate="one_to_one")["right"]).to_numpy(dtype=float)
        diff = diff[np.isfinite(diff)]
        if diff.size:
            draws = rng.choice(diff, size=(BOOTSTRAP_ITERATIONS, diff.size), replace=True).mean(axis=1)
            compare_df.loc[idx, "ci95_high"] = float(np.quantile(draws, 0.975))
    compare_df.to_csv(OUT_COMPARE, index=False)
    evaluation.to_csv(OUT_EVAL, index=False)
    station.to_csv(OUT_STATION, index=False)
    types.to_csv(OUT_TYPE, index=False)
    scenarios.to_csv(OUT_SCENARIO, index=False)
    selection.to_csv(OUT_SELECTION, index=False)
    fit.to_csv(OUT_FIT, index=False)
    from sklearn.metrics import average_precision_score
    pooled_rows: list[dict[str, object]] = []
    for method in METHODS:
        method_station = station[station["method"].eq(method)]
        tp = int(method_station["tp"].sum())
        fp = int(method_station["fp"].sum())
        fn = int(method_station["fn"].sum())
        tn = int(method_station["tn"].sum())
        events = int(method_station["events"].sum())
